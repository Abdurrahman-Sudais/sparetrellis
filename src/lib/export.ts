import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export type Cell = string | number | null | undefined;

function escapeCsv(v: Cell): string {
  const s = v === null || v === undefined ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function download(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function exportCsv(filename: string, headers: string[], rows: Cell[][], preamble: string[] = []) {
  const lines = [...preamble.map((p) => `# ${p}`), headers.map(escapeCsv).join(","), ...rows.map((r) => r.map(escapeCsv).join(","))];
  download(new Blob([lines.join("\n")], { type: "text/csv;charset=utf-8" }), filename);
}

export interface PdfOptions {
  title: string;
  subtitle?: string;
  summary?: [string, string][];
  notes?: string[];
  headers: string[];
  rows: Cell[][];
  filename: string;
}

export function exportPdf({ title, subtitle, summary = [], notes = [], headers, rows, filename }: PdfOptions) {
  const doc = new jsPDF({ orientation: headers.length > 6 ? "landscape" : "portrait", unit: "pt", format: "a4" });
  const w = doc.internal.pageSize.getWidth();

  doc.setFillColor(15, 26, 46);
  doc.rect(0, 0, w, 64, "F");
  doc.setFillColor(245, 158, 11);
  doc.rect(0, 64, w, 3, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("SpareTrellis", 32, 30);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text("Find the spare parts already in stock.", 32, 46);
  doc.text(new Date().toLocaleString("en-GB"), w - 32, 30, { align: "right" });

  doc.setTextColor(20, 24, 33);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text(title, 32, 96);
  let y = 112;
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(90, 98, 115);
    doc.text(subtitle, 32, y);
    y += 16;
  }
  if (summary.length) {
    autoTable(doc, {
      startY: y,
      body: summary,
      theme: "plain",
      styles: { fontSize: 9, cellPadding: 3 },
      columnStyles: { 0: { fontStyle: "bold", cellWidth: 200 } },
      margin: { left: 32, right: 32 },
    });
    // @ts-expect-error lastAutoTable is added by the plugin
    y = doc.lastAutoTable.finalY + 10;
  }
  if (notes.length) {
    doc.setFontSize(8);
    doc.setTextColor(146, 64, 14);
    for (const n of notes) {
      const lines = doc.splitTextToSize(`Note: ${n}`, w - 64);
      doc.text(lines, 32, y);
      y += lines.length * 10 + 2;
    }
    y += 4;
  }
  autoTable(doc, {
    startY: y,
    head: [headers],
    body: rows.map((r) => r.map((c) => (c === null || c === undefined ? "" : String(c)))),
    styles: { fontSize: 7.5, cellPadding: 4, overflow: "linebreak" },
    headStyles: { fillColor: [23, 38, 64], textColor: 255, fontStyle: "bold" },
    alternateRowStyles: { fillColor: [246, 247, 249] },
    margin: { left: 32, right: 32 },
    didDrawPage: () => {
      doc.setFontSize(7);
      doc.setTextColor(140);
      doc.text("Generated by SpareTrellis — demonstration data. AI outputs are suggestions requiring human verification.", 32, doc.internal.pageSize.getHeight() - 16);
    },
  });
  doc.save(filename);
}
